import { expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  checkDefaultImplementationDigest,
  defaultImplementationSourceDigest,
} from "../../../scripts/default-implementation-digest";
import {
  defaultPedagogicalTheory,
  PLATFORM_PEDAGOGY_RELEASE,
  pedagogicalTheoryDigest,
  resolvePedagogy,
} from "../src";

test("platform release executable identity matches the current sorted Core source inventory", () => {
  checkDefaultImplementationDigest();
  expect(defaultPedagogicalTheory.implementationDigest).toBe(defaultImplementationSourceDigest());
  const resolved = resolvePedagogy(
    { get: () => PLATFORM_PEDAGOGY_RELEASE },
    PLATFORM_PEDAGOGY_RELEASE.ref,
  );
  expect(resolved.theory.digest).toBe(pedagogicalTheoryDigest(defaultPedagogicalTheory));
});

test("executable inventory reacts to source edits and paths, not generated identity or Skill Markdown", () => {
  const root = mkdtempSync(join(tmpdir(), "concept-executable-"));
  try {
    mkdirSync(join(root, "pedagogy/default"), { recursive: true });
    writeFileSync(join(root, "b.ts"), "export const value = 1;\n");
    writeFileSync(join(root, "a.ts"), "export const other = 2;\n");
    const first = defaultImplementationSourceDigest(root);
    writeFileSync(
      join(root, "pedagogy/default/implementation-digest.ts"),
      "ignored generated bytes",
    );
    writeFileSync(join(root, "SKILL.md"), "separate catalog identity");
    expect(defaultImplementationSourceDigest(root)).toBe(first);
    writeFileSync(join(root, "a.ts"), "export const other = 3;\n");
    expect(defaultImplementationSourceDigest(root)).not.toBe(first);
    writeFileSync(join(root, "a.ts"), "export const other = 2;\n");
    expect(defaultImplementationSourceDigest(root)).toBe(first);
    writeFileSync(join(root, "c.ts"), "export const other = 2;\n");
    expect(defaultImplementationSourceDigest(root)).not.toBe(first);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
